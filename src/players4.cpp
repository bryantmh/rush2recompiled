// func_803B9478 (car select) once every player has chosen, before the race is started: true to stay on the screen.
int rush2_players4_cars_chosen(uint8_t* rdram, recomp_context* ctx) {
    int total = rush2::players4::joined_players(rdram);
    if (total <= 2) {
        car_round = 0;
        return false;
    }
    swap_rounds(rdram, total);
    if (car_round == 0) {
        MEM_H(0, (int32_t)rush2::players4::num_players) = (int16_t)(total - 2);
        save_car_entries(rdram);
        car_round = 1;
        call(rdram, ctx, menu_play_sound_80064908, sound_join);
        call(rdram, ctx, carselect_build_list_803B81F0, 0); // Ends the screen; it sets itself up again next frame.
        return true;
    }
    MEM_H(0, (int32_t)rush2::players4::num_players) = 2;
    restore_car_entries(rdram);
    car_round = 0;
    return false;
}

// func_803BC048 (car select text), after a panel's "PLAYER %d" label is formatted at $sp + 0x6C: the second round's
// panels are players 3 and 4.
void rush2_players4_car_label(uint8_t* rdram, recomp_context* ctx) {
    if (car_round == 0) {
        return;
    }
    int32_t text = (int32_t)ctx->r29 + 0x6C;
    for (int i = 0; i < 32 && MEM_B(i, text) != 0; i++) {
        char c = (char)MEM_B(i, text);
        if (c >= '1' && c <= '2' && MEM_B(i + 1, text) == 0) {
            MEM_B(i, text) = (int8_t)(c + 2);
        }
    }
}

// func_803B9478 (car select) when a player backs out: true to stay on the screen.
int rush2_players4_cars_back(uint8_t* rdram, recomp_context* ctx) {
    if (car_round == 0) {
        return false;
    }
    swap_rounds(rdram, rush2::players4::joined_players(rdram));
    MEM_H(0, (int32_t)rush2::players4::num_players) = 2;
    car_round = 0;
    call(rdram, ctx, menu_play_sound_80064908, sound_back);
    call(rdram, ctx, carselect_build_list_803B81F0, 0);
    return true;
}

