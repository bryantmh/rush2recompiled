// func_800B4EB0, after the frame tasks are set up at startup. Copies the moved arrays to their new homes, sets up the
// records of players 3 and 4, and points the frame tasks at the bigger graphics buffers.
void rush2_players4_init(uint8_t* rdram, recomp_context* ctx) {
    for (const Move& m : moves) {
        copy_rdram(rdram, m.new_start, m.old_start, m.old_end - m.old_start);
    }
    // The free element pointers point into the element array, which moved and grew: point them at the new one.
    for (int i = 0; i < hud_pool_size; i++) {
        int32_t at = (int32_t)(hud_element_pointers + i * 4);
        uint32_t element = (uint32_t)MEM_W(0, at);
        if (i < old_hud_pool_size && element >= old_hud_element_array &&
            element < old_hud_element_array + old_hud_pool_size * hud_element_size) {
            MEM_W(0, at) = (int32_t)(hud_element_array + (element - old_hud_element_array));
        }
        else if (i >= old_hud_pool_size) {
            MEM_W(0, at) = (int32_t)(hud_element_array + i * hud_element_size);
        }
    }

    // Records 3 and 4 take the place of the string table that moved; they start as copies of record 2 (its button
    // map and settings) with their own cars and no controller.
    for (int player = 2; player < rush2::players4::max_players; player++) {
        int32_t rec = rush2::players4::record(player);
        copy_rdram(rdram, (uint32_t)rec, (uint32_t)rush2::players4::record(1), record_size);
        MEM_B(record_car, rec) = (int8_t)player;
        MEM_B(record_port, rec) = (int8_t)no_port;
        MEM_W(record_buffer, rec) = 0;
    }

    // Views 2 and 3 follow cars 2 and 3.
    MEM_B(2, (int32_t)view_cars) = 2;
    MEM_B(3, (int32_t)view_cars) = 3;

    for (int i = 0; i < 2; i++) {
        MEM_W(task_buffer[i], (int32_t)task_structs) = (int32_t)frame_blocks[i];
    }
    rush2::players4::frame(rdram);
}

// func_803AA92C (each menu screen's per-frame step), on the game's main thread.
void rush2_players4_menu(uint8_t* rdram, recomp_context* ctx) {
    // Back in the menus, which are built for two players, after a race with more.
    if (joining_allowed(MEM_W(0, (int32_t)game_state)) && player_count(rdram) > 2) {
        MEM_H(0, (int32_t)rush2::players4::num_players) = 2;
        MEM_H(0, (int32_t)rush2::players4::num_views) = 2;
    }
    update_joining(rdram, ctx);
}

// func_800A6B58 (START on the title screen), once it has found the port that pressed START ($s0, and $s1 = port * 2):
// player 1 is the first port with a controller or the keyboard in the Players tab, whichever device pressed START.
// Otherwise, after a race, START from the device set up as player 2 or 3 (pressed to get through the results) made it
// player 1, and it then did nothing on "PRESS START TO JOIN".
void rush2_players4_title_port(uint8_t* rdram, recomp_context* ctx) {
    for (int port = 0; port < ports; port++) {
        if (rush2::input::port_has_device(port)) {
            ctx->r16 = port;
            ctx->r17 = port * 2;
            return;
        }
    }
}

// func_800AE670 (the game's state machine), each frame.
void rush2_players4_state(uint8_t* rdram, recomp_context* ctx) {
    int32_t state = MEM_W(0, (int32_t)game_state);
    if (state == 4 && player_count(rdram) > 2) {
        MEM_H(0, (int32_t)rush2::players4::num_players) = 2;
        MEM_H(0, (int32_t)rush2::players4::num_views) = 2;
    }
}

// func_800A0FB4, before it draws the dark box behind player 1's or 2's place once finished: split side by side or in
// quadrants, the boxes are left out (they're placed for views stacked top and bottom, and players 3 and 4 have none).
int rush2_players4_skip_finish_box(uint8_t* rdram, recomp_context* ctx) {
    return rush2::splitscreen::is_side_by_side(rdram) || rush2::splitscreen::quadrant_views(rdram) != 0;
}

// func_800AE670, once players 1 and 2 have finished the race: whether players 3 and 4 have too.
int rush2_players4_all_finished(uint8_t* rdram, recomp_context* ctx) {
    for (int player = 2; player < player_count(rdram); player++) {
        int car = MEM_BU(record_car, rush2::players4::record(player));
        if (MEM_B(car_finished, (int32_t)(car_states + car * car_state_size)) == 0) {
            return 0;
        }
    }
    return 1;
}

// func_800AE670, as a race is set up (before the cars are given to the players, func_800A580C): players 3 and 4 who
// have joined take part.
void rush2_players4_race_start(uint8_t* rdram, recomp_context* ctx) {
    int total = rush2::players4::joined_players(rdram);
    if (player_count(rdram) == 2 && total > 2) {
        MEM_H(0, (int32_t)rush2::players4::num_players) = (int16_t)total;
        MEM_H(0, (int32_t)rush2::players4::num_views) = (int16_t)total;
    }
    rush2::players4::frame(rdram);
}

// func_800A5ADC, after the fog of views 0 and 1 is set up (func_80081074). Sets up views 2 and 3.
void rush2_players4_race_views(uint8_t* rdram, recomp_context* ctx) {
    for (int view = 2; view < MEM_H(0, (int32_t)rush2::players4::num_views); view++) {
        setup_view_fog(rdram, ctx, view);
    }
}

// func_800AE670, after the per-frame fog update of views 0 and 1 (in game states 3 and 10).
void rush2_players4_frame_views(uint8_t* rdram, recomp_context* ctx) {
    int32_t state = MEM_W(0, (int32_t)game_state);
    if (state != 3 && state != 0xA) {
        return;
    }
    for (int view = 2; view < MEM_H(0, (int32_t)rush2::players4::num_views); view++) {
        setup_view_fog(rdram, ctx, view);
    }
}

// func_800B45B4 (frame setup), after it sets the frame's graphics buffer pointers from the task. Moves the matrix pool
// and the second display list to their places in the bigger buffer.
void rush2_players4_frame_buffers(uint8_t* rdram, recomp_context* ctx) {
    uint32_t base = (uint32_t)MEM_W(0, (int32_t)view_matrices);
    MEM_W(0, (int32_t)matrix_pool) = (int32_t)(base + frame_pool_start);
    MEM_W(0, (int32_t)dl2_cursor) = (int32_t)(base + frame_dl2_start);

    // The controller thread (func_80076DE0) reads only the ports its map (D_8010C150, -1 = none) had a controller on
    // when it last scanned: at boot (where the runtime's scan reports only one port present) and when the Controller
    // Pak code asks it to (D_80023060, not set from here: that would break the pak code's exchange with it). A port
    // whose controller is assigned or found later was never read, so the map follows the ports' controllers (and the
    // ports an input script presses on, which test players may also sit on).
    for (int port = 0; port < ports; port++) {
        bool read = rush2::input::is_port_connected(port) || rush2::input::is_port_scripted(port);
        MEM_B(port, (int32_t)controller_map) = (int8_t)(read ? port : -1);
        // The pak thread only registers a port with the rumble code (mask D_800D4E75) if a controller was there when
        // it last scanned, so a controller assigned to port 3 or 4 later never rumbled. Those ports report a Rumble Pak
        // (src/pak.cpp), so the rumble update's own osMotorInit finds it once the bit is set.
        if (read && port >= 2) {
            MEM_B(0, (int32_t)rumble_mask) = (int8_t)(MEM_BU(0, (int32_t)rumble_mask) | (1 << port));
        }
    }
}

// func_8007B518 (draws a scene graph level for a view, $a2), after the offset of the view's link in a node ($s0 =
// view * 2): views 2 and 3 follow the links of views 0 and 1.
void rush2_players4_list_offset(uint8_t* rdram, recomp_context* ctx) {
    ctx->r16 = ((uint32_t)ctx->r6 & 1) * 2;
}

// func_8007C624, after the view's bit is made to test a world polygon's view mask ($t7 = 1 << view, the view at
// $sp+0x180): views 2 and 3 also draw the polygons of views 0 and 1. $fp = the polygon. The arrows over the other
// players' cars (src/arrows.cpp) each belong to one view of the four.
void rush2_players4_poly_mask(uint8_t* rdram, recomp_context* ctx) {
    if (rush2::arrows::single_view((uint32_t)ctx->r30)) {
        return;
    }
    int32_t view = MEM_W(0x180, ctx->r29);
    ctx->r15 = (uint32_t)ctx->r15 | (1u << (view & 1));
}

