// Three and four player races.
//
// Rush 2 keeps most race state per car (up to 8 cars, human players first), but a few things exist once per player
// or per view, sized for two: the player records, cameras, views and their viewports, and a few smaller arrays. Those
// move to bigger copies in free RDRAM (tools/players4/relocate.py generates the us.toml patches), or grow in place
// where only a small variable sat after them and that variable moved instead. This file copies the moved data at
// startup, fills in the records of players 3 and 4, and keeps the per-frame graphics buffers big enough for four
// views.
//
// Graphics buffers. Each frame's task (D_800D4060, two of them) has a 0xC980 byte buffer whose first 0x180 bytes hold
// the views' viewports, sky vertices, projections and root modelviews, laid out for two views. After them come three
// regions that grow up without bounds checks: a matrix pool (D_80022FE4) from +0x180, the display list (D_80022FD8)
// from +0x5900 and a second display list (D_80022FDC) from +0x9780. us.toml moves the per-view entries to a four-view
// layout (viewports +0x00, vertices +0x40, projections +0x80, modelviews +0x180, the shared modelview +0x280), and the
// buffers move to 256 KB blocks: the display list keeps its place at +0x5900 (the task setup, func_800B4214, assumes
// it), the second one starts at +0x18000 and the matrix pool at +0x28000.

