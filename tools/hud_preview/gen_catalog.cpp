// Writes src/hud_catalog_rom.inc, the race HUD catalog's facts from the ROM (docs/hud_layout.md#catalog): the race
// HUD setup's and the finish overlay's layout tables, and the size and opaque texels of every image they name, in
// each language. Run it again if the catalog needs another table or image.
//
//   hud_catalog_gen [ROM] [OUT]   (ROM: rush2.us.recomp.z64, OUT: src/hud_catalog_rom.inc)
//
// Build from Git Bash: cmd //c "tools\hud_preview\build.bat"   (writes tmp\hud_preview\hud_catalog_gen.exe)
#include <cstdio>
#include <set>
#include <string>

#include "hud_rom.h"

namespace {
    constexpr uint32_t hud_table = 0x800C2DB4;    // hud_race_setup_widgets_800A06F8's
    constexpr int hud_count = 0x70;
    constexpr uint32_t finish_table = 0x800BF328; // hud_race_finish_overlay_build_800A0FB4's
    constexpr int finish_count = 7;

    struct Opaque {
        int x0, y0, x1, y1;
        bool operator==(const Opaque&) const = default;
    };
    Opaque opaque_of(const hud_rom::Image& im) {
        Opaque o{ im.w, im.h, -1, -1 };
        for (int y = 0; y < im.h; y++) {
            for (int x = 0; x < im.w; x++) {
                if (im.rgba[((size_t)y * im.w + x) * 4 + 3] == 0) continue;
                o.x0 = std::min(o.x0, x);
                o.y0 = std::min(o.y0, y);
                o.x1 = std::max(o.x1, x);
                o.y1 = std::max(o.y1, y);
            }
        }
        if (o.x1 < 0) o = Opaque{ 0, 0, im.w - 1, im.h - 1 };
        return o;
    }
}

int main(int argc, char** argv) {
    std::string rom_path = argc > 1 ? argv[1] : "rush2.us.recomp.z64";
    std::string out_path = argc > 2 ? argv[2] : "src/hud_catalog_rom.inc";
    hud_rom::Rom rom;
    std::string error;
    if (!rom.load(rom_path, error)) {
        std::fprintf(stderr, "%s\n", error.c_str());
        return 1;
    }
    FILE* f = std::fopen(out_path.c_str(), "wb");
    if (f == nullptr) {
        std::fprintf(stderr, "can't write %s\n", out_path.c_str());
        return 1;
    }
    std::fprintf(f,
                 "// Generated by tools/hud_preview/gen_catalog.cpp from the Rush 2 (USA) ROM; do not edit by hand.\n"
                 "// The race HUD's layout tables and the images they name (src/hud_catalog.cpp, docs/hud_layout.md#catalog).\n\n");
    std::set<std::string> names;
    auto table = [&](const char* what, const char* var, uint32_t vram, int count) {
        std::fprintf(f, "// %s (0x%08X): image, x, y, callback, parameter.\n", what, vram);
        std::fprintf(f, "constexpr RomEntry %s[] = {\n", var);
        int i = 0;
        for (const hud_rom::Entry& e : rom.table(vram, count)) {
            std::fprintf(f, "    { \"%s\", %d, %d, 0x%08X, 0x%08X },  // %d\n", e.name.c_str(), e.x, e.y, e.callback, e.param, i++);
            if (!e.name.empty() && e.name != "-1") names.insert(e.name);
        }
        std::fprintf(f, "};\n\n");
    };
    table("The race HUD setup's table (hud_race_setup_widgets_800A06F8)", "rom_hud_table", hud_table, hud_count);
    table("The finish overlay's table (hud_race_finish_overlay_build_800A0FB4)", "rom_finish_table", finish_table, finish_count);
    std::fprintf(f, "// Images: name, language (-1: the same in every one; 0 English, 1 French, 2 German), width, height, opaque\n"
                    "// texels (x0, y0, x1, y1, top row 0). From assets 0x12 and 0x13, and 0x16-0x18 by language.\n");
    std::fprintf(f, "constexpr Texture rom_textures[] = {\n");
    for (const std::string& n : names) {
        const hud_rom::Image* im[3] = { rom.image(n, 0), rom.image(n, 1), rom.image(n, 2) };
        if (im[0] == nullptr) {
            std::fprintf(stderr, "image %s isn't in the HUD's containers\n", n.c_str());
            continue;
        }
        bool same = true;
        for (int l = 1; l < 3; l++) {
            same = same && im[l] != nullptr && im[l]->w == im[0]->w && im[l]->h == im[0]->h && opaque_of(*im[l]) == opaque_of(*im[0]);
        }
        for (int l = 0; l < (same ? 1 : 3); l++) {
            if (im[l] == nullptr) continue;
            Opaque o = opaque_of(*im[l]);
            std::fprintf(f, "    { \"%s\", %d, %d, %d, { %d, %d, %d, %d } },\n", n.c_str(), same ? -1 : l, im[l]->w, im[l]->h,
                         o.x0, o.y0, o.x1, o.y1);
        }
    }
    std::fprintf(f, "};\n");
    std::fclose(f);
    std::printf("wrote %s (%zu images)\n", out_path.c_str(), names.size());
    return 0;
}
