def medium(shapes):
    """Shapes drawn in Medium's texels (font 9, caps from y = 0.73 to 9.53), in Large's: the punctuation is drawn over
    Medium, the biggest font that has it."""
    k = (CAP[1] - CAP[0]) / (9.53 - 0.73)

    def pt(x, y):
        return round(x * k, 3), round(CAP[0] + (y - 0.73) * k, 3)

    out = []
    for shape in shapes:
        if shape[0] in 'ph':
            out.append((shape[0], [(*pt(x, y), (r[0] * k, r[1] * k) if isinstance(r, tuple) else r * k)
                                   for x, y, r in shape[1]]))
        else:
            out.append(('s', [pt(x, y) for x, y in shape[1]], shape[2] * k, shape[3]))
    return out


